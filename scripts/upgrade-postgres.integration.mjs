import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import test from "node:test";

const run = (args, options = {}) =>
  execFileSync("docker", args, { encoding: "utf8", stdio: ["pipe", "pipe", "pipe"], ...options });

test(
  "Compose blocks legacy data; migration preserves records, sequences, and history",
  { timeout: 240_000 },
  async () => {
    const project = `parcelis-upgrade-test-${Date.now()}`;
    const directory = mkdtempSync(resolve(tmpdir(), "parcelis-upgrade-"));
    const composeFile = resolve(directory, "compose.json");
    const actual = JSON.parse(run(["compose", "-f", "docker-compose-dev.yml", "config", "--format", "json"]));
    const sourceVolume = `${project}_postgres-data`;
    const source = `${project}-source`;
    const user = "parcelis";
    const database = "parcelis_test";
    const service = actual.services["postgres-service"];
    writeFileSync(
      composeFile,
      JSON.stringify({
        services: {
          "postgres-service": {
            image: service.image,
            entrypoint: service.entrypoint,
            command: service.command,
            environment: { POSTGRES_USER: user, POSTGRES_PASSWORD: "test-password", POSTGRES_DB: database },
            volumes: ["postgres-data:/legacy:ro", "postgres18-data:/var/lib/postgresql"],
            healthcheck: {
              test: ["CMD-SHELL", "pg_isready -h 127.0.0.1 -U parcelis -d parcelis_test"],
              interval: "1s",
              timeout: "2s",
              retries: 30,
            },
          },
        },
        volumes: { "postgres-data": {}, "postgres18-data": {} },
      }),
    );
    const compose = ["compose", "-p", project, "-f", composeFile];
    const wait = async (container) => {
      for (let attempt = 0; attempt < 60; attempt++) {
        try {
          run(["exec", container, "pg_isready", "-h", "127.0.0.1", "-U", user, "-d", database]);
          return;
        } catch {
          await new Promise((done) => setTimeout(done, 1000));
        }
      }
      throw new Error(`Database not ready: ${container}`);
    };
    const migrate = (...args) =>
      execFileSync(
        process.execPath,
        ["scripts/upgrade-postgres.mjs", ...args, "--", "-p", project, "-f", composeFile],
        { encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] },
      );
    try {
      run([...compose, "up", "-d", "--wait"]);
      assert.match(
        run([
          ...compose,
          "exec",
          "-T",
          "postgres-service",
          "psql",
          "-XAt",
          "-U",
          user,
          "-d",
          database,
          "-c",
          "SHOW server_version;",
        ]),
        /^18\./,
      );
      run([...compose, "down", "-v"]);
      run(["volume", "create", sourceVolume]);
      run([
        "run",
        "-d",
        "--name",
        source,
        "--network",
        "none",
        "-v",
        `${sourceVolume}:/var/lib/postgresql/data`,
        "-e",
        `POSTGRES_USER=${user}`,
        "-e",
        "POSTGRES_PASSWORD=test-password",
        "-e",
        `POSTGRES_DB=${database}`,
        "postgres:16-alpine",
      ]);
      await wait(source);
      run(["exec", "-i", source, "psql", "-v", "ON_ERROR_STOP=1", "-U", user, "-d", database], {
        input: `
      CREATE TABLE records (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
      INSERT INTO records (name) VALUES ('retained tenant'), ('retained property');
      DELETE FROM records WHERE id = 2;
      CREATE TABLE _prisma_migrations (id text PRIMARY KEY, checksum text);
      INSERT INTO _prisma_migrations VALUES ('existing-migration', 'original-checksum');
    `,
      });
      const extraDatabase = "parcelis_extra_test";
      run(["exec", source, "createdb", "-U", user, extraDatabase]);
      run(["exec", "-i", source, "psql", "-v", "ON_ERROR_STOP=1", "-U", user, "-d", extraDatabase], {
        input:
          "CREATE TABLE test_records (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text); INSERT INTO test_records (name) VALUES ('preserved test record');",
      });
      run(["stop", source]);
      run(["rm", source]);
      assert.throws(() => run([...compose, "up", "-d", "--wait"]));
      assert.match(run([...compose, "logs", "postgres-service"]), /startup blocked to protect your data/);
      assert.match(migrate(), /Preflight passed/);
      const migrationOutput = migrate("--execute", "--backup-dir", resolve(directory, "backup"));
      assert.match(migrationOutput, /Restore verified/);
      assert.match(migrationOutput, /Other databases left in the PostgreSQL 16 volume: "parcelis_extra_test"/);
      assert.throws(() => migrate(), /Command failed/);
      run([...compose, "up", "-d", "--wait"]);
      const sql = (query) =>
        run([
          ...compose,
          "exec",
          "-T",
          "postgres-service",
          "psql",
          "-XAt",
          "-U",
          user,
          "-d",
          database,
          "-c",
          query,
        ]).trim();
      assert.match(sql("SHOW server_version;"), /^18\./);
      assert.equal(sql("SELECT name FROM records;"), "retained tenant");
      assert.equal(sql("INSERT INTO records (name) VALUES ('new record') RETURNING id;"), "3\nINSERT 0 1");
      assert.equal(sql("SELECT checksum FROM _prisma_migrations;"), "original-checksum");
      assert.equal(sql("SELECT count(*) FROM pg_database WHERE datname = 'parcelis_extra_test';"), "0");
      run([
        "run",
        "-d",
        "--name",
        source,
        "--network",
        "none",
        "-v",
        `${sourceVolume}:/var/lib/postgresql/data`,
        "postgres:16-alpine",
      ]);
      await wait(source);
      assert.equal(
        run([
          "exec",
          source,
          "psql",
          "-XAt",
          "-U",
          user,
          "-d",
          extraDatabase,
          "-c",
          "SELECT name FROM test_records;",
        ]).trim(),
        "preserved test record",
      );
      run(["stop", source]);
      run(["rm", source]);
      assert.equal(
        run([
          "run",
          "--rm",
          "--network",
          "none",
          "-v",
          `${sourceVolume}:/data:ro`,
          "--entrypoint",
          "cat",
          "postgres:18-alpine",
          "/data/PG_VERSION",
        ]).trim(),
        "16",
      );
    } finally {
      if (run(["ps", "-aq", "--filter", `name=^${source}$`]).trim()) run(["rm", "-f", source]);
      run([...compose, "down", "-v"]);
    }
  },
);
